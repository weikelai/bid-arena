CREATE TABLE agent_jobs (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 user_id BIGINT NOT NULL,
 auction_id BIGINT NOT NULL,
 token_id BIGINT NOT NULL,
 max_bid BIGINT NOT NULL,
 max_bids INT NOT NULL,
 poll_ms INT NOT NULL,
 timeout_ms INT NOT NULL,
 max_errors INT NOT NULL,
 desired VARCHAR(16) NOT NULL DEFAULT 'STOPPED',
 state VARCHAR(16) NOT NULL DEFAULT 'STOPPED',
 bid_count INT NOT NULL DEFAULT 0,
 error_count INT NOT NULL DEFAULT 0,
 pending_id VARCHAR(100) NULL,
 pending_amount BIGINT NULL,
 owner VARCHAR(64) NULL,
 lease_until DATETIME(6) NULL,
 lease_epoch BIGINT NOT NULL DEFAULT 0,
 next_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 last_decision DATETIME(6) NULL,
 last_result VARCHAR(200) NULL,
 last_error VARCHAR(80) NULL,
 current_price BIGINT NULL,
 leader_id BIGINT NULL,
 final_result JSON NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(auction_id) REFERENCES auctions(id),
 FOREIGN KEY(token_id) REFERENCES agent_tokens(id),
 UNIQUE KEY uq_job_token(token_id),
 INDEX ix_job_claim(next_at,lease_until),
 CHECK(max_bid BETWEEN 110 AND 1000000000 AND max_bids BETWEEN 1 AND 10000),
 CHECK(poll_ms BETWEEN 3000 AND 60000 AND timeout_ms BETWEEN 1000 AND 10000 AND max_errors BETWEEN 1 AND 100),
 CHECK(desired IN ('RUNNING','PAUSED','STOPPED')),
 CHECK(state IN ('STOPPED','STARTING','WAITING','RUNNING','PAUSED','STOPPING','FINISHED','ERROR')),
 CHECK((pending_id IS NULL)=(pending_amount IS NULL))
) ENGINE=InnoDB;
CREATE TABLE agent_job_events (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 type VARCHAR(32) NOT NULL,
 detail VARCHAR(200) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(job_id) REFERENCES agent_jobs(id),
 INDEX ix_job_events(job_id,id)
) ENGINE=InnoDB;
